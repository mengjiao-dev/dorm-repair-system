CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(40) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, display_name VARCHAR(40) NOT NULL,
 role VARCHAR(20) NOT NULL, building VARCHAR(40), room VARCHAR(20), skill VARCHAR(40), enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS category (id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(40) NOT NULL UNIQUE, enabled BOOLEAN NOT NULL DEFAULT TRUE);
CREATE TABLE IF NOT EXISTS repair_order (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_no VARCHAR(40) NOT NULL UNIQUE,
 student_id BIGINT NOT NULL, building VARCHAR(40) NOT NULL, room VARCHAR(20) NOT NULL,
 category VARCHAR(40) NOT NULL, title VARCHAR(80) NOT NULL, description VARCHAR(1000) NOT NULL,
 appointment VARCHAR(100) NOT NULL, status VARCHAR(30) NOT NULL, assignee_id BIGINT,
 version INT NOT NULL DEFAULT 0, round_no INT NOT NULL DEFAULT 1,
 request_id VARCHAR(64) NOT NULL, request_hash VARCHAR(64) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL, updated_at TIMESTAMP(3) NOT NULL,
 accepted_at TIMESTAMP(3), finished_at TIMESTAMP(3),
 CONSTRAINT uk_request UNIQUE(student_id,request_id),
 FOREIGN KEY(student_id) REFERENCES app_user(id), FOREIGN KEY(assignee_id) REFERENCES app_user(id)
);
CREATE TABLE IF NOT EXISTS repair_log (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, actor_id BIGINT NOT NULL,
 action VARCHAR(30) NOT NULL, note VARCHAR(1000) NOT NULL, created_at TIMESTAMP(3) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES repair_order(id), FOREIGN KEY(actor_id) REFERENCES app_user(id)
);
CREATE TABLE IF NOT EXISTS evaluation (
 order_id BIGINT PRIMARY KEY, score INT NOT NULL, content VARCHAR(500) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL, FOREIGN KEY(order_id) REFERENCES repair_order(id), CHECK(score BETWEEN 1 AND 5)
);
CREATE TABLE IF NOT EXISTS attachment (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, uploader_id BIGINT NOT NULL,
 storage_key VARCHAR(80) NOT NULL, media_type VARCHAR(30) NOT NULL, original_name VARCHAR(150) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL, FOREIGN KEY(order_id) REFERENCES repair_order(id)
);
CREATE TABLE IF NOT EXISTS outbox_event (
 id VARCHAR(36) PRIMARY KEY, order_id BIGINT NOT NULL, recipient_id BIGINT NOT NULL,
 message VARCHAR(300) NOT NULL, state VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 attempts INT NOT NULL DEFAULT 0, next_retry_at TIMESTAMP(3) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL, last_error VARCHAR(300)
);
CREATE TABLE IF NOT EXISTS notification (
 id VARCHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL, order_id BIGINT NOT NULL,
 message VARCHAR(300) NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP(3) NOT NULL
);
